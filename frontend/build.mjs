// Build into the existing server allowlist; no new runtime routes or CSP changes.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('.', import.meta.url));
for (const entry of ['demo', 'login']) await build({
  absWorkingDir: root, entryPoints: [`${entry}-app.js`], outfile: `${root}${entry}.js`,
  bundle: true, format: 'esm', target: ['es2022'],
  // Compact the bundled graphics library; keep the shared sign-in/font asset stable.
  minifyWhitespace: entry === 'demo',
  external: ['./contracts.js', './session.js', './login.js'], loader: { '.woff2': 'binary' },
  banner: { js: '// Generated by frontend/build.mjs. Edit the source modules, then npm run build --prefix frontend.' },
});
const sheets = ['fonts.css', 'helix.css', 'result-chart.css', 'demo-app.css', 'question.css', 'intake.css'];
const css = await Promise.all(sheets.map(name => readFile(new URL(name, import.meta.url), 'utf8')));
await writeFile(new URL('demo.css', import.meta.url), '/* Generated by frontend/build.mjs. Edit the source stylesheets. */\n' + css.join('\n'));
